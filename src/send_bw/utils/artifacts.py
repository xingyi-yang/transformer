"""Artifact IO, hashing, cache keys, manifests and structured logging."""

from __future__ import annotations

import datetime as dt
import hashlib
import json
import logging
import platform
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

import pandas as pd

from send_bw.utils.security import RedactingFilter, redact

LOGGER_NAME = "send_bw"


def get_logger() -> logging.Logger:
    return logging.getLogger(LOGGER_NAME)


class _JsonFormatter(logging.Formatter):
    def format(self, record: logging.LogRecord) -> str:
        return json.dumps(
            {
                "ts": dt.datetime.now(dt.UTC).isoformat(),
                "level": record.levelname,
                "logger": record.name,
                "msg": redact(record.getMessage()),
            }
        )


def setup_logging(log_file: Path | None = None, level: int = logging.INFO) -> logging.Logger:
    logger = get_logger()
    logger.setLevel(level)
    logger.handlers.clear()
    console = logging.StreamHandler(sys.stdout)
    console.setFormatter(logging.Formatter("%(levelname)s %(message)s"))
    console.addFilter(RedactingFilter())
    logger.addHandler(console)
    if log_file is not None:
        log_file.parent.mkdir(parents=True, exist_ok=True)
        fh = logging.FileHandler(log_file, encoding="utf-8")
        fh.setFormatter(_JsonFormatter())
        fh.addFilter(RedactingFilter())
        logger.addHandler(fh)
    logger.propagate = False
    return logger


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def file_hash(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def dir_hash(path: Path, patterns: tuple[str, ...] = ("*",)) -> str:
    h = hashlib.sha256()
    files = sorted({p for pat in patterns for p in Path(path).rglob(pat) if p.is_file()})
    for p in files:
        h.update(str(p.relative_to(path)).replace("\\", "/").encode())
        h.update(file_hash(p).encode())
    return h.hexdigest()


def json_default(o: Any) -> Any:
    import numpy as np

    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (Path,)):
        return str(o)
    if isinstance(o, (dt.date, dt.datetime)):
        return o.isoformat()
    if isinstance(o, set):
        return sorted(o)
    raise TypeError(f"Not JSON serializable: {type(o)}")


def stable_json(obj: Any) -> str:
    return json.dumps(obj, sort_keys=True, default=json_default)


def cache_key(*parts: Any) -> str:
    return sha256_bytes(stable_json(list(parts)).encode())[:16]


def write_json(path: Path, obj: Any) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, sort_keys=True, default=json_default), encoding="utf-8")
    return path


def read_json(path: Path) -> Any:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def write_parquet(path: Path, df: pd.DataFrame) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_parquet(path, index=False)
    return path


def safe_rmtree_generated(path: Path, marker: str = ".send_bw_generated") -> None:
    """Remove a directory only if it was created by this tool (never user files)."""
    path = Path(path)
    if not path.exists():
        return
    if not (path / marker).exists():
        raise PermissionError(f"Refusing to delete {path}: not marked as generated by send_bw")
    shutil.rmtree(path)


def mark_generated(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)
    (path / ".send_bw_generated").write_text("generated by send_bw; safe to delete\n", encoding="utf-8")


def git_revision(cwd: Path | None = None) -> str | None:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=cwd, capture_output=True, text=True, timeout=5, check=False
        )
        return out.stdout.strip() or None
    except (OSError, subprocess.SubprocessError):
        return None


def software_versions() -> dict[str, str | None]:
    import importlib.metadata as md

    pkgs = ["numpy", "pandas", "scipy", "scikit-learn", "pyarrow", "pydantic", "torch", "pymc", "arviz",
            "nutpie", "pytensor", "matplotlib", "pyreadstat", "snowflake-connector-python"]
    vers: dict[str, str | None] = {"python": platform.python_version(), "platform": platform.platform()}
    for p in pkgs:
        try:
            vers[p] = md.version(p)
        except md.PackageNotFoundError:
            vers[p] = None
    return vers


class Manifest:
    """Accumulates lineage for a run and writes manifest.json."""

    def __init__(self, run_dir: Path, config: dict, config_path: str | None):
        self.run_dir = Path(run_dir)
        self.data: dict[str, Any] = {
            "created_utc": dt.datetime.now(dt.UTC).isoformat(),
            "config_path": config_path,
            "config_hash": cache_key(config),
            "seed": config.get("seed"),
            "git_revision": git_revision(),
            "software": software_versions(),
            "stages": {},
            "synthetic_data": bool(config.get("synthetic", {}).get("enabled", False)),
        }
        path = self.run_dir / "manifest.json"
        if path.exists():
            old = read_json(path)
            self.data["stages"] = old.get("stages", {})

    def record_stage(self, name: str, **info: Any) -> None:
        info["completed_utc"] = dt.datetime.now(dt.UTC).isoformat()
        self.data["stages"][name] = info
        self.save()

    def save(self) -> None:
        write_json(self.run_dir / "manifest.json", self.data)
