MODEL_CLASSES = {}
REQUIRED_MODELS = ("spline", "transformer", "bayesian")
OPTIONAL_TRAIN = ("tft",)


def model_class(name: str):
    """Required benchmark classes only. Optional TFT is never registered here."""
    if name in OPTIONAL_TRAIN:
        raise KeyError(f"{name!r} is an optional early-history adapter, not a required benchmark")
    if not MODEL_CLASSES:
        from send_bw.models.spline import SplineModel
        from send_bw.models.transformer import TransformerModel

        MODEL_CLASSES.update({"spline": SplineModel, "transformer": TransformerModel})
        try:
            from send_bw.models.bayesian import BayesianModel

            MODEL_CLASSES["bayesian"] = BayesianModel
        except ImportError:  # pragma: no cover
            pass
    return MODEL_CLASSES[name]


class Run:
    def __init__(self, config_path: str | Path, overrides: dict[str, Any] | None = None):
        self.config_path = str(config_path)
        with open(config_path, encoding="utf-8") as f:
            self.cfg: dict[str, Any] = yaml.safe_load(f)
        for k, v in (overrides or {}).items():
            self.cfg[k] = v
        src = self.cfg.get("source", {})
        if src.get("type") == "snowflake" and not src.get("snowflake", {}).get("authorized", False):
            raise PermissionError("Snowflake source is disabled: set authorized: true only with explicit "
                                  "written authorization (nothing was created or contacted)")
        self.dir = Path(self.cfg.get("output_dir", f"runs/{self.cfg.get('run_name', 'run')}"))
        try:
            self.dir.mkdir(parents=True, exist_ok=True)
        except OSError as e:
            raise FileNotFoundError(f"output_dir {self.dir} is not accessible; point it at approved storage") from e
        (self.dir / ".send_bw_generated").write_text("generated by send_bw\n", encoding="utf-8")
        self.log = setup_logging(self.dir / "log.jsonl")
        self.manifest = Manifest(self.dir, self.cfg, self.config_path)
        self.seed = int(self.cfg.get("seed", 0))

    def p(self, *parts: str) -> Path:
        out = self.dir.joinpath(*parts)
        out.parent.mkdir(parents=True, exist_ok=True)
        return out

    def _skip(self, stage: str, key: str, force: bool) -> bool:
        st = self.manifest.data["stages"].get(stage)
        if not force and st and st.get("key") == key:
            self.log.info(f"[{stage}] cached (key {key}); use --force to rerun")
            return True
        return False

    # ------------------------------------------------------------------ generate
    def generate(self, force: bool = False) -> None:
        syn = self.cfg.get("synthetic", {})
        if not syn.get("enabled", False):
            self.log.info("[generate] synthetic generation disabled for this config")
            return
        out = Path(syn.get("out_dir", self.dir / "synthetic"))
        gen_seed = int(self.cfg.get("generate_seed", self.seed))
        key = cache_key(syn, gen_seed)
        if self._skip("generate", key, force) and out.exists():
            return
        if out.exists():
            safe_rmtree_generated(out)
        t0 = time.time()
        info = generate_dataset(syn, out, seed=gen_seed)
        self.manifest.record_stage("generate", key=key, seconds=time.time() - t0, **info,
                                   send_hash=dir_hash(Path(info["send_dir"])),
                                   generate_seed=gen_seed,
                                   label="SYNTHETIC SEND-like data (not certified SEND-conformant)")
        self.log.info(f"[generate] {info['n_studies']} synthetic studies -> {out}")

    # ------------------------------------------------------------------ source / ingest
    def source(self):
        mapping = load_mapping(self.cfg["mapping"])
        src = build_source(self.cfg["source"], domain_aliases=mapping.domain_aliases)
        return src, mapping

    def inspect_source(self) -> dict[str, Any]:
        src, _ = self.source()
        info = src.inspect()
        write_json(self.p("qc", "source_inspection.json"), info)
        return info

    def ingest(self, force: bool = False) -> CanonicalTables:
        src_cfg = self.cfg["source"]
        upstream = self.manifest.data["stages"].get("generate", {}).get("send_hash")
        if src_cfg.get("type") == "local" and upstream is None:
            upstream = dir_hash(Path(src_cfg["root"]))
        key = cache_key(src_cfg, Path(self.cfg["mapping"]).read_text(encoding="utf-8"), upstream)
        if self._skip("ingest", key, force):
            return self.load_canonical()
        src, mapping = self.source()
        t0 = time.time()
        tables, report = harmonize(src, mapping)
        for name, df in tables.tables.items():
            write_parquet(self.p("canonical", f"{name}.parquet"), df)
        prov = {"source_id": src.source_id, "mapping_version": mapping.mapping_version,
                "send_version": mapping.send_version, "source_config": {k: v for k, v in src_cfg.items()
                                                                         if k != "snowflake"},
                "extraction_log": getattr(src, "extraction_log", None)}
        write_json(self.p("canonical", "provenance.json"), prov)
        write_json(self.p("qc", "mapping_report.json"), report)
        tables["quarantine"].to_csv(self.p("qc", "quarantine.csv"), index=False)
        self.write_data_dictionary()
        self.manifest.record_stage("ingest", key=key, seconds=time.time() - t0,
                                   n_bw=len(tables["bw_obs"]), n_animals=len(tables["animal_context"]),
                                   n_quarantine=len(tables["quarantine"]), mapping_version=mapping.mapping_version)
        self.log.info(f"[ingest] {len(tables['bw_obs'])} weights, {len(tables['animal_context'])} animals, "
                      f"{len(tables['quarantine'])} quarantined/flagged records")
        return tables

    def load_canonical(self) -> CanonicalTables:
        t = CanonicalTables()
        for f in sorted(self.p("canonical", "x").parent.glob("*.parquet")):
            t[f.stem] = pd.read_parquet(f)
        return t

    def write_data_dictionary(self) -> None:
        lines = ["# Data dictionary (canonical tables)", "",
                 "Generated by send_bw. DAY = elapsed days from the reference date (default DM.RFSTDTC); "
                 "the reference date is elapsed day 0 and SEND study day 1 (no day 0).", ""]
        for t, cols in CANONICAL_SCHEMAS.items():
            lines += [f"## {t}", "", "| column | type | required |", "|---|---|---|"]
            lines += [f"| {c} | {k} | {'yes' if r else 'no'} |" for c, (k, r) in cols.items()]
            lines.append("")
        lines += ["## Feature availability registry", "", "| feature | availability |", "|---|---|"]
        lines += [f"| {k} | {v} |" for k, v in FEATURE_REGISTRY.items()]
        lines += [f"| {k}* | {v} |" for k, v in PREFIX_REGISTRY.items()]
        self.p("qc", "data_dictionary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # ------------------------------------------------------------------ prepare
    def prepare(self, force: bool = False) -> dict[str, Any]:
        key = cache_key(self.manifest.data["stages"].get("ingest", {}).get("key"), self.cfg.get("cohort"),
                        self.cfg.get("splits"), self.seed)
        if self._skip("prepare", key, force) and self.p("splits", "splits.csv").exists():
            return self.load_prepared()
        t0 = time.time()
        t = self.load_canonical()
        ccfg = CohortConfig.from_dict(self.cfg.get("cohort"))
        target_cfg = ccfg.target_only()
        target_cohort = select_cohort(t, target_cfg)
        from send_bw.sharing import uses_donors

        donor_mode = uses_donors(ccfg.sharing) and bool(ccfg.donor_species)
        qc_cohort = select_cohort(t, ccfg) if donor_mode else target_cohort
        qc_cohort.exclusions.to_csv(self.p("qc", "exclusions.csv"), index=False)
        qc_cohort.completeness.to_csv(self.p("qc", "completeness.csv"), index=False)
        excl = (qc_cohort.exclusions.assign(REASON=qc_cohort.exclusions["EXCLUSION_REASON"].str.split(";"))
                .explode("REASON").groupby("REASON").size().to_dict()) if len(qc_cohort.exclusions) else {}
        sc = t["study_context"]
        in_scope = sc[(sc["SPECIES"] == ccfg.species.upper()) & sc["STUDY_CLASS"].isin(ccfg.study_classes)]
        in_scope = in_scope[in_scope["STUDYID"].isin(set(target_cohort.animals["STUDYID"]))]
        scfg = dict(self.cfg.get("splits", {}))
        comp = (t["arm_regimen"].dropna(subset=["COMPOUND_ID"]).groupby("STUDYID")["COMPOUND_ID"].first().to_dict())
        scfg["_study_compound"] = comp
        reuse = scfg.get("reuse_target_from")
        if reuse:
            src = Path(str(reuse))
            splits_target = load_frozen_splits(src / "target_splits")
            missing = sorted(set(splits_target["STUDYID"].astype(str)) - set(in_scope["STUDYID"].astype(str)))
            if missing:
                raise ValueError(f"reused target studies missing from current cohort: {missing}")
            freeze_splits(splits_target, self.p("splits", "target_splits"))
            tman = freeze_target_manifests(splits_target, self.p("splits", "target_manifest.json"))
            src_man = read_json(src / "target_manifest.json")
            for name in ("validation", "test", "all_target"):
                if tman[name]["hash"] != src_man[name]["hash"]:
                    raise ValueError(f"reused target splits changed {name} hash")
        else:
            if scfg.get("compound_holdout_auto"):
                req_comp = set()
                if self.cfg.get("design", {}).get("request"):
                    with open(self.cfg["design"]["request"], encoding="utf-8") as f:
                        req_comp = {g.get("compound_id") for g in yaml.safe_load(f)["groups"]}
                counts = pd.Series({s: c for s, c in comp.items() if s in set(in_scope["STUDYID"])}).value_counts()
                counts = counts[~counts.index.isin(req_comp)]
                scfg["compound_holdout"] = list(
                    counts.sort_values(kind="stable").index[: int(scfg["compound_holdout_auto"])])
            splits_target = make_study_splits(in_scope, scfg, self.seed)
            freeze_splits(splits_target, self.p("splits", "target_splits"))
            tman = freeze_target_manifests(splits_target, self.p("splits", "target_manifest.json"))
        sparse_n = scfg.get("sparse_target_train_n")
        sparse_meta = None
        if sparse_n is not None:
            splits_target, sparse_meta = compose_sparse_target_train(splits_target, int(sparse_n))
            sparse_meta["target_manifest_validation_hash"] = tman["validation"]["hash"]
            sparse_meta["target_manifest_test_hash"] = tman["test"]["hash"]
            write_json(self.p("splits", "sparse_target_train.json"), sparse_meta)
        donor_parts_a, donor_parts_o = [], []
        if ccfg.donor_species:
            for ds in ccfg.donor_species:
                dc = select_cohort(t, replace(target_cfg, species=str(ds).upper()))
                if len(dc.animals):
                    donor_parts_a.append(dc.animals)
                    donor_parts_o.append(dc.obs)
        if donor_parts_a:
            donor_animals = pd.concat(donor_parts_a, ignore_index=True)
            donor_obs = pd.concat(donor_parts_o, ignore_index=True)
            donor_ids_all = donor_study_order(donor_animals["STUDYID"])
        else:
            donor_animals = target_cohort.animals.iloc[0:0]
            donor_obs = target_cohort.obs.iloc[0:0]
            donor_ids_all = []
        from send_bw.share_policy import resolve_donors

        explicit = scfg.get("selected_donor_ids")
        rule = scfg.get("donor_rule") or ("prefix" if donor_mode else "zero")
        picked = resolve_donors(
            donor_ids_all,
            k=int(ccfg.n_donor_studies) if donor_mode else 0,
            rule=str(rule),
            rng_seed=scfg.get("donor_rng_seed"),
            explicit=list(explicit) if explicit is not None else None,
            allow_donors=bool(donor_mode or explicit is not None),
        )
        selected = list(picked["selected"])
        k = int(picked["k"])
        write_json(self.p("splits", "donor_order.json"), {
            "studyids": donor_ids_all, "k": k, "selected": selected,
            "sharing": ccfg.sharing, "donor_species": list(ccfg.donor_species),
            "rule": picked.get("rule"), "rng_seed": picked.get("rng_seed"),
            "test_outcomes_used": False, "validation_outcomes_used": False,
            "eligible_recorded": True,
        })
        splits = compose_train_with_donors(splits_target, selected, len(selected))
        h = freeze_splits(splits, self.p("splits", "splits"))
        animals = target_cohort.animals.copy()
        obs = target_cohort.obs.copy()
        if selected:
            animals = pd.concat([animals, donor_animals[donor_animals["STUDYID"].isin(selected)]],
                                ignore_index=True)
            obs = pd.concat([obs, donor_obs[donor_obs["STUDYID"].isin(selected)]], ignore_index=True)
        tr = set(splits.loc[splits["SPLIT"] == "train", "STUDYID"].astype(str))
        feat_cfg = self.cfg.get("features") or {}
        fixed_schema = bool(feat_cfg.get("fixed_schema"))
        declared = []
        if fixed_schema or donor_mode:
            declared = [ccfg.species.upper()] + [str(s).upper() for s in ccfg.donor_species]
        if selected and donor_mode:
            sharing_for_spec = ccfg.sharing
        else:
            sharing_for_spec = "context_specific"
        spec = FeatureSpec.fit(animals[animals["STUDYID"].astype(str).isin(tr)],
                               obs[obs["STUDYID"].astype(str).isin(tr)], t["compound_reference"],
                               ccfg.species.upper(), sharing=sharing_for_spec,
                               declared_species=declared or None, fixed_schema=fixed_schema)
        write_json(self.p("features", "feature_spec.json"), spec.to_dict())
        write_parquet(self.p("cohort", "animals.parquet"), animals)
        write_parquet(self.p("cohort", "obs.parquet"), obs)
        write_json(self.p("qc", "qc_report.json"), {"checks": qc_cohort.qc_checks, "limitations": qc_cohort.limitations,
                                                    "exclusion_counts": excl,
                                                    "n_eligible_animals": len(animals),
                                                    "n_model_obs": len(obs),
                                                    "n_target_eligible_animals": len(target_cohort.animals),
                                                    "sharing": ccfg.sharing,
                                                    "n_donor_studies_requested": int(ccfg.n_donor_studies),
                                                    "n_donor_studies_selected": k,
                                                    "donor_studyids_selected": selected,
                                                    "sparse_target_train": sparse_meta})
        self.manifest.record_stage("prepare", key=key, split_hash=h, split_counts=splits["SPLIT"].value_counts().to_dict(),
                                   compound_holdout=scfg.get("compound_holdout", []),
                                   n_eligible_animals=len(animals), seconds=time.time() - t0,
                                   sharing=ccfg.sharing, n_donor_studies=k,
                                   target_manifest=tman,
                                   sparse_target_train=sparse_meta,
                                   train_seed=self.seed)
        self.log.info(f"[prepare] splits {splits['SPLIT'].value_counts().to_dict()} (frozen hash {h})")
        return self.load_prepared()

    def load_prepared(self) -> dict[str, Any]:
        splits = load_frozen_splits(self.p("splits", "splits"))
        spec = FeatureSpec.from_dict(read_json(self.p("features", "feature_spec.json")))
        cref = pd.read_parquet(self.p("canonical", "compound_reference.parquet"))
        full = ModelData(pd.read_parquet(self.p("cohort", "animals.parquet")),
                         pd.read_parquet(self.p("cohort", "obs.parquet")), cref, spec)
        data = {s: full.subset(splits.loc[splits["SPLIT"] == s, "STUDYID"]) for s in splits["SPLIT"].unique()}
        return {"splits": splits, "spec": spec, "data": data, "compound_ref": cref}

    # ------------------------------------------------------------------ train
    def enabled_models(self) -> list[str]:
        return [m for m in REQUIRED_MODELS if self.cfg.get("models", {}).get(m, {}).get("enabled")]

    def train(self, models: list[str] | None = None, force: bool = False) -> dict[str, Any]:
        prep = self.load_prepared()
        tr, va = prep["data"]["train"], prep["data"]["validation"]
        out = {}
        requested = list(models) if models else self.enabled_models()
        for name in requested:
            if name in OPTIONAL_TRAIN:
                continue
            mcfg = dict(self.cfg["models"][name])
            mcfg.setdefault("seed", self.seed)
            key = cache_key(self.manifest.data["stages"]["prepare"]["key"], mcfg,
                            self.manifest.data["stages"].get("train_spline", {}).get("key") if name == "transformer" else None)
            if self._skip(f"train_{name}", key, force) and self.p("models", name, "model.json").exists():
                continue
            if name == "bayesian":
                try:
                    import pymc  # noqa: F401
                except ImportError:
                    self.manifest.record_stage("train_bayesian", key=None, status="not_run",
                                               reason="bayesian extra not installed")
                    continue
            if name == "transformer":
                mcfg["shared_covariance"] = model_class("spline").load(self.p("models", "spline")).cov
            t0 = time.time()
            try:
                model = model_class(name)()
                hist = model.fit(tr, va, mcfg)
                model.save(self.p("models", name))
                write_json(self.p("models", name, "training_history.json"), hist)
            except Exception as e:  # noqa: BLE001
                if name != "bayesian":
                    raise
                reason = f"Bayesian inference failed: {type(e).__name__}: {e}"
                from send_bw.evaluation.uncertainty import sampling_diagnosis

                diag = sampling_diagnosis({}, compile_error=reason, status="failed")
                self.manifest.record_stage("train_bayesian", key=None, status="failed", reason=reason,
                                           counted_as_successful_benchmark=False,
                                           sampling_diagnosis=diag)
                write_json(self.p("evaluation", "bayesian_gate.json"),
                           {"status": "failed", "reliable": False,
                            "counted_as_successful_benchmark": False, "reason": reason})
                write_json(self.p("evaluation", "sampling_diagnosis.json"), diag)
                self.log.info(f"[train] bayesian failed: {reason}")
                continue
            info = {"key": key, "seconds": time.time() - t0, "status": "trained"}
            if name == "bayesian":
                info["reliable"] = bool(model.diagnostics["main"]["reliable"])
                info["diagnostics_summary"] = {k: model.diagnostics["main"][k] for k in
                                               ["rhat_max", "ess_bulk_min", "ess_tail_min", "divergences"]}
                info["counted_as_successful_benchmark"] = bool(info["reliable"])
                from send_bw.sharing import is_selective, selective_record

                sharing = getattr(tr.spec, "sharing", "context_specific")
                if is_selective(sharing):
                    hist["selective_sharing"] = selective_record(
                        "bayesian", "regularized" if sharing == "selective_regularized" else "v1")
                    write_json(self.p("models", name, "training_history.json"), hist)
                info["matched_data"] = {
                    "matched_to": ["spline", "transformer"],
                    "same_prepare_key": self.manifest.data["stages"].get("prepare", {}).get("key"),
                    "train_studyids_hash": cache_key(sorted(tr.studies)),
                    "validation_studyids_hash": cache_key(sorted(va.studies)),
                    "train_seed": self.seed,
                    "generate_seed": self.cfg.get("generate_seed"),
                    "note": "Bayesian uses the same prepared train/validation as spline and transformer.",
                }
                write_json(self.p("evaluation", "matched_data.json"), info["matched_data"])
                from send_bw.evaluation.uncertainty import sampling_diagnosis

                info["sampling_diagnosis"] = sampling_diagnosis(model.diagnostics.get("main") or {})
                write_json(self.p("evaluation", "sampling_diagnosis.json"), info["sampling_diagnosis"])
            self.manifest.record_stage(f"train_{name}", **info)
            out[name] = info
            self.log.info(f"[train] {name} done in {info['seconds']:.1f}s")
        from send_bw.models.optional_adapters import optional_status

        opt = optional_status(self.cfg.get("models", {}))
        opt = self._train_optional(prep, opt, force)
        write_json(self.p("models", "optional_models_status.json"), opt)
        self.manifest.record_stage("optional_models", key=None, status={k: v["status"] for k, v in opt.items()})
        return out

    def _train_optional(self, prep: dict[str, Any], opt: dict[str, dict[str, Any]], force: bool) -> dict[str, dict[str, Any]]:
        """Train optional adapters that are adapter_ready. Failures are recorded, not raised."""
        tft = opt.get("tft") or {}
        if tft.get("status") != "adapter_ready":
            return opt
        mcfg = dict((self.cfg.get("models", {}).get("optional", {}) or {}).get("tft") or {})
        mcfg.setdefault("seed", self.seed)
        mcfg.setdefault("early_history_window_day",
                        self.cfg.get("evaluation", {}).get("early_history_window_day", 14))
        key = cache_key(self.manifest.data["stages"].get("prepare", {}).get("key"), mcfg)
        if self._skip("train_tft", key, force) and self.p("models", "tft", "model.json").exists():
            tft["status"] = "trained"
            tft["reason"] = ("cached; early-history only; not a required benchmark; "
                             "not used for design or pre-study")
            opt["tft"] = tft
            return opt
        try:
            from send_bw.models.tft import TFTEarlyHistoryModel

            t0 = time.time()
            model = TFTEarlyHistoryModel()
            hist = model.fit(prep["data"]["train"], prep["data"]["validation"], mcfg)
            model.save(self.p("models", "tft"))
            write_json(self.p("models", "tft", "training_history.json"), hist)
            tft["status"] = "trained"
            tft["reason"] = ("trained for early-history forecasting only; not a required benchmark; "
                             "not used for design or pre-study")
            tft.setdefault("extra", {})["history"] = {k: hist[k] for k in hist
                                                       if k in ("n_train_series", "n_val_series", "n_train_obs",
                                                                "max_epochs", "quantiles", "note")}
            self.manifest.record_stage("train_tft", key=key, seconds=time.time() - t0, status="trained")
            self.log.info(f"[train] tft (optional early-history) done in {time.time() - t0:.1f}s")
        except Exception as e:  # noqa: BLE001
            tft["status"] = "failed"
            tft["reason"] = f"TFT training failed: {type(e).__name__}: {e}"
            self.manifest.record_stage("train_tft", key=None, status="failed", reason=tft["reason"])
            self.log.info(f"[train] tft failed: {tft['reason']}")
        opt["tft"] = tft
        return opt

    def load_model(self, name: str):
        return model_class(name).load(self.p("models", name))

    def load_optional_model(self, name: str):
        if name != "tft":
            raise KeyError(f"unknown optional model {name!r}")
        from send_bw.models.tft import TFTEarlyHistoryModel

        return TFTEarlyHistoryModel.load(self.p("models", name))

    def available_models(self) -> list[str]:
        """Required benchmarks only. Optional TFT is never a design/pre-study generator."""
        return [m for m in REQUIRED_MODELS if self.p("models", m, "model.json").exists()]

    def optional_trained(self) -> list[str]:
        return [m for m in OPTIONAL_TRAIN if self.p("models", m, "model.json").exists()]

    # ------------------------------------------------------------------ evaluate
    def evaluate(self, force: bool = False) -> dict[str, Any]:
        from send_bw.evaluation.forecast import evaluate_early_history, evaluate_prestudy, evaluation_pack

        prep = self.load_prepared()
        ecfg = self.cfg.get("evaluation", {})
        tasks = set(ecfg.get("tasks") or ["pre_study", "early_history"])
        if "predose_conditioned" in tasks:
            tasks.add("pre_study")
        res: dict[str, Any] = {}
        t_start = time.time()
        for name in self.available_models():
            model = self.load_model(name)
            for split in [s for s in ("test", "test_compound_holdout") if s in prep["data"]]:
                d = prep["data"][split]
                if not len(d.obs):
                    continue
                t0 = time.time()
                if "pre_study" in tasks:
                    r = evaluate_prestudy(model, d, int(ecfg.get("n_draws", 200)), self.seed + 17,
                                          float(ecfg.get("contrast_day", 28)))
                    r["summary"]["split"] = split
                    r["summary"]["task_alias"] = "predose_conditioned"
                    r["by_sex_horizon"].to_csv(self.p("evaluation", f"{name}_{split}_by_sex_horizon.csv"), index=False)
                    r["per_study"].to_csv(self.p("evaluation", f"{name}_{split}_per_study.csv"), index=False)
                    pack = evaluation_pack(r)
                    write_json(self.p("evaluation", f"{name}_{split}_evaluation_pack.json"), pack)
                    r["summary"]["evaluation_pack"] = {
                        k: pack[k] for k in ("individual", "group_mean", "contrast", "temporal")
                    }
                    res[f"{name}|{split}|pre_study"] = r["summary"]
                if "early_history" in tasks:
                    eh = evaluate_early_history(model, d, float(ecfg.get("early_history_window_day", 14)))
                    eh["split"] = split
                    res[f"{name}|{split}|early_history"] = eh
                if "sparse_history" in tasks:
                    from send_bw.evaluation.sparse import evaluate_sparse_grid

                    encoders = list(ecfg.get("sparse_encoders") or ["W0", "W1", "Wlast14", "Wall14"])
                    sp = evaluate_sparse_grid(model, d, encoders=encoders,
                                              n_draws=int(ecfg.get("n_draws", 80)),
                                              seed=self.seed + 17,
                                              contrast_day=float(ecfg.get("contrast_day", 28)))
                    sp["split"] = split
                    write_json(self.p("evaluation", f"{name}_{split}_sparse.json"), sp)
                    res[f"{name}|{split}|sparse_history"] = {
                        "task": "sparse_history", "model": name, "split": split,
                        "encoders": {k: {kk: vv for kk, vv in v.items() if kk != "summary"}
                                     | ({"rmse_log": (v.get("summary") or {}).get("study_balanced", {}).get("rmse_log")}
                                        if v.get("summary") else {})
                                     for k, v in (sp.get("encoders") or {}).items()},
                    }
                self.log.info(f"[evaluate] {name}/{split} in {time.time() - t0:.1f}s")
        if "early_history" in tasks:
            for name in self.optional_trained():
                model = self.load_optional_model(name)
                for split in [s for s in ("test", "test_compound_holdout") if s in prep["data"]]:
                    d = prep["data"][split]
                    if not len(d.obs):
                        continue
                    t0 = time.time()
                    eh = evaluate_early_history(model, d, float(ecfg.get("early_history_window_day", 14)))
                    eh["split"] = split
                    res[f"{name}|{split}|early_history"] = eh
                    self.log.info(f"[evaluate] {name}/{split} early-history only in {time.time() - t0:.1f}s")
        write_json(self.p("evaluation", "metrics.json"), res)
        s0_path = ecfg.get("context_specific_metrics")
        if s0_path and Path(s0_path).exists():
            from send_bw.evaluation.transfer import build_transfer_table

            s0_all = read_json(s0_path)
            k = int((self.cfg.get("cohort") or {}).get("n_donor_studies") or 0)
            tables = {}
            for key, sk in res.items():
                if not key.endswith("pre_study"):
                    continue
                s0 = s0_all.get(key)
                if not s0:
                    continue
                tables[key] = build_transfer_table(s0, [(k, sk)], model=sk.get("model"))
            if tables:
                write_json(self.p("evaluation", "transfer_table.json"), tables)
        self.manifest.record_stage("evaluate", key=None, n_results=len(res), seconds=time.time() - t_start)
        return res

    # ------------------------------------------------------------------ design
    def design(self, force: bool = False) -> dict[str, Any]:
        from send_bw.simulation.workflow import run_design_workflow

        dcfg = self.cfg.get("design", {})
        if not dcfg.get("request"):
            return {"status": "not_run", "reason": "no design request configured"}
        truth_dir = None
        if self.cfg.get("synthetic", {}).get("enabled"):
            truth_dir = self.manifest.data["stages"].get("generate", {}).get("truth_dir") or self.cfg.get("truth_dir")
        models = {m: self.load_model(m) for m in self.available_models()}
        t0 = time.time()
        out = run_design_workflow(models, dcfg, self.p("design", "x").parent, self.seed, truth_dir, self.log)
        self.manifest.record_stage("design", key=None, status=out.get("status"), seconds=time.time() - t0)
        return out

    # ------------------------------------------------------------------ report
    def report(self) -> Path:
        from send_bw.evaluation.report import build_report

        path = build_report(self)
        self.manifest.record_stage("report", key=None, path=str(path))
        return path

    def validate_real(self) -> dict[str, Any]:
        """Real-data qualification stage 1 artifacts: ingestion, mapping and QC only (no model claims)."""
        self.inspect_source()
        t = self.ingest(force=True)
        cohort = select_cohort(t, CohortConfig.from_dict(self.cfg.get("cohort")))
        rep = {"qualification_stage_achieved": 1 if not self.cfg.get("synthetic", {}).get("enabled") else 0,
               "stage_definitions": QUALIFICATION_STAGES, "qc_checks": cohort.qc_checks,
               "limitations": cohort.limitations, "n_eligible_animals": len(cohort.animals),
               "note": "Stage 1 = implemented and mock-tested pipeline run on these extracts. It does NOT certify "
                       "real-data readiness; stages 2-5 require authorized pilot reconciliation, scientist review "
                       "of mappings, held-out real-study evaluation and prospective shadow validation."}
        write_json(self.p("qc", "real_data_qualification.json"), rep)
        return rep

    def run_all(self, force: bool = False) -> None:
        t0 = time.time()
        self.generate(force)
        self.inspect_source()
        self.ingest(force)
        self.prepare(force)
        self.train(force=force)
        self.evaluate(force)
        self.design(force)
        self.report()
        self.log.info(f"[run-all] finished in {time.time() - t0:.0f}s; report at {self.dir / 'report' / 'report.md'}")


QUALIFICATION_STAGES = {
    1: "implemented and mock-tested; pipeline executed on the extracts",
    2: "authorized pilot reconciliation against source records",
    3: "scientist-reviewed cohort, arm and regimen mappings",
    4: "held-out real-study evaluation",
    5: "prospective shadow validation",
}


